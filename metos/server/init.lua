-- metos server. Packed into metos.com (redbean) as /.init.lua by package.sh.
--
-- Double-clicking metos.com:
--   * serves the folder it sits in (the stick), so index.html and kb/ come
--     straight from the stick, never from a copy inside the program
--   * reads kb/ live: a .md file dropped into kb/ shows up on reload
--   * opens the browser on metos
--   * saves entries written in the app into kb/, then refreshes kb.js and
--     CONTENTS.md so the no-program fallback (opening index.html) stays current
--
-- Only this computer can save. Anyone else reaching the server (a phone on
-- the same Wi-Fi, when started with -l 0.0.0.0) can read but not write.

-- arg[-1] is the program itself (metos.com). It can be relative to where it
-- was started from, so resolve it to a full path first.
local exe = arg and arg[-1] or 'metos.com'
local here = path.dirname(unix.realpath(exe) or exe)
local kbdir = path.join(here, 'kb')
ProgramDirectory(here)

-- ---- reading the knowledge base -------------------------------------------

local function isEntry(name)
  return name:match('^[^_.][^/\\]*%.md$') or name:match('^[^_.][^/\\]*%.txt$')
end

local function listEntries()
  local names = {}
  local dir = unix.opendir(kbdir)
  if dir then
    for name, kind in dir do
      if kind == unix.DT_REG and isEntry(name) then names[#names + 1] = name end
    end
  end
  table.sort(names)
  local files = {}
  for _, name in ipairs(names) do
    files[#files + 1] = { name = name, text = Slurp(path.join(kbdir, name)) or '' }
  end
  return files
end

local function bundle()
  return {
    built = os.date('!%Y-%m-%d'),
    vocab = Slurp(path.join(here, 'vocab.txt')) or '',
    files = listEntries()
  }
end

-- ---- keeping the fallback files current -----------------------------------

-- Same output as build.js: kb.js lets index.html work without any program.
local function writeBundle(b)
  local json = EncodeJson(b, { pretty = true }) or '{}'
  Barf(path.join(here, 'kb.js'),
    '// Generated by build.js from kb/ and vocab.txt. Do not edit by hand.\n' ..
    'window.METOS_BUNDLE = ' .. json .. ';\n')
end

-- CONTENTS.md: the table of contents, readable with no program at all.
local function writeContents(b)
  local lines = { '# metos: contents', '', 'Every entry in kb/, by title. Open any file in kb/ with a text editor to read it.', '' }
  local rows = {}
  for _, f in ipairs(b.files) do
    local title = f.text:match('^title:%s*([^\n]+)') or f.text:match('\ntitle:%s*([^\n]+)') or f.name
    local tags = f.text:match('\ntags:%s*([^\n]+)') or ''
    rows[#rows + 1] = { title = title, name = f.name, tags = tags }
  end
  table.sort(rows, function (a, b) return a.title:lower() < b.title:lower() end)
  for _, r in ipairs(rows) do
    lines[#lines + 1] = '- ' .. r.title .. ' — kb/' .. r.name .. (r.tags ~= '' and ('  (' .. r.tags .. ')') or '')
  end
  Barf(path.join(here, 'CONTENTS.md'), table.concat(lines, '\n') .. '\n')
end

-- ---- requests --------------------------------------------------------------

local function json(status, t)
  SetStatus(status)
  SetHeader('Content-Type', 'application/json; charset=utf-8')
  SetHeader('Cache-Control', 'no-store')
  Write(EncodeJson(t))
end

function OnHttpRequest()
  local p = GetPath()

  if p == '/api/kb' then
    return json(200, bundle())
  end

  if p == '/api/entry' then
    if GetMethod() ~= 'POST' then return json(405, { error = 'Use POST to save an entry.' }) end
    -- GetClientAddr, not GetRemoteAddr: the latter can be steered by a
    -- forwarded-for header. Only a connection from this computer may write.
    local ip = GetClientAddr()
    if not ip or not IsLoopbackIp(ip) then
      return json(403, { error = 'Only the computer the stick is plugged into can save entries.' })
    end
    local name = GetParam('name') or ''
    if not isEntry(name) or name:find('%.%.') then
      return json(400, { error = 'Entry file names look like yarrow.md: no folders, not starting with _ or a dot.' })
    end
    local body = GetBody() or ''
    if #body == 0 or #body > 2 * 1024 * 1024 then
      return json(400, { error = 'An entry must have text and be under 2 MB.' })
    end
    unix.makedirs(kbdir)
    local ok, err = Barf(path.join(kbdir, name), body)
    if not ok then return json(500, { error = 'Could not write to the stick: ' .. tostring(err) }) end
    local b = bundle()
    writeBundle(b)
    writeContents(b)
    return json(200, { ok = true, name = name, entries = #b.files })
  end

  return Route()
end

-- Refresh the fallback files at start, in case entries were dropped in by hand.
do
  local b = bundle()
  pcall(writeBundle, b)
  pcall(writeContents, b)
end

LaunchBrowser('/')
