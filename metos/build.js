#!/usr/bin/env node
/*
 * Packs kb/*.md, kb/*.txt and vocab.txt into kb.js, so index.html works when
 * opened straight from a USB stick or SD card (file://), with no server.
 *
 *   node build.js
 *
 * Run it after dropping new entries into kb/. In the browser you can also
 * skip this step and use "Open folder" to read the kb folder directly.
 */
'use strict';
var fs = require('fs');
var path = require('path');

var here = __dirname;
var kbDir = path.join(here, 'kb');

var files = fs.readdirSync(kbDir)
  .filter(function (f) { return /\.(md|txt)$/i.test(f) && !/^_/.test(f); })
  .sort()
  .map(function (f) { return { name: f, text: fs.readFileSync(path.join(kbDir, f), 'utf8') }; });

var vocabPath = path.join(here, 'vocab.txt');
var vocab = fs.existsSync(vocabPath) ? fs.readFileSync(vocabPath, 'utf8') : '';

var bundle = { built: new Date().toISOString().slice(0, 10), vocab: vocab, files: files };
var out = '// Generated by build.js from kb/ and vocab.txt. Do not edit by hand.\n' +
  'window.METOS_BUNDLE = ' + JSON.stringify(bundle, null, 1) + ';\n';

fs.writeFileSync(path.join(here, 'kb.js'), out);
console.log('kb.js: ' + files.length + ' entries, ' + Math.round(out.length / 1024) + ' KB');

// CONTENTS.md: the table of contents, readable with no program at all.
// metos.com (server/init.lua) writes the same file when entries are saved.
function header(text, key) {
  var m = new RegExp('(^|\\n)' + key + ':\\s*([^\\n]+)').exec(text);
  return m ? m[2].trim() : '';
}
var rows = files.map(function (f) {
  return { title: header(f.text, 'title') || f.name, name: f.name, tags: header(f.text, 'tags') };
}).sort(function (a, b) { return a.title.toLowerCase() < b.title.toLowerCase() ? -1 : 1; });
var contents = ['# metos: contents', '', 'Every entry in kb/, by title. Open any file in kb/ with a text editor to read it.', '']
  .concat(rows.map(function (r) { return '- ' + r.title + ' — kb/' + r.name + (r.tags ? '  (' + r.tags + ')' : ''); }))
  .join('\n') + '\n';
fs.writeFileSync(path.join(here, 'CONTENTS.md'), contents);
console.log('CONTENTS.md: ' + rows.length + ' entries');
